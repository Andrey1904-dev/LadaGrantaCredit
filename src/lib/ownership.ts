/**
 * Остаток гарантии по времени и пробегу.
 * Возвращает null, если неизвестна дата покупки (тогда считать не от чего).
 */
export function warrantyLeft(
  item: WarrantyItem,
  purchaseDate: string | null,
  mileage: number,
  startMileage = 0,
): { monthsLeft: number; kmLeft: number | null; used: number; expired: boolean } | null {
  if (!purchaseDate) return null
  const start = new Date(purchaseDate)
  if (Number.isNaN(start.getTime())) return null

  const now = new Date()
  const monthsPassed =
    (now.getFullYear() - start.getFullYear()) * 12 +
    (now.getMonth() - start.getMonth()) +
    (now.getDate() >= start.getDate() ? 0 : -1)
  const monthsLeft = item.months - monthsPassed
  const kmPassed = Math.max(0, mileage - startMileage)
  const kmLeft = item.km > 0 ? item.km - kmPassed : null

  const byTime = monthsPassed / item.months
  const byKm = item.km > 0 ? kmPassed / item.km : 0
  return {
    monthsLeft,
    kmLeft,
    used: Math.min(1, Math.max(0, Math.max(byTime, byKm))),
    expired: monthsLeft <= 0 || (kmLeft !== null && kmLeft <= 0),
  }
}

